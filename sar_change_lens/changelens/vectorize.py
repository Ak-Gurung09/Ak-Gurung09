"""Raster change classes -> GeoJSON polygons with per-object evidence.

The dashboard shows *objects* ("this 1.3 km2 patch"), not raw pixels, because
objects carry the evidence a person needs: area, how much darker it got, how
confident we are, and whether the terrain makes flooding plausible.
"""

from __future__ import annotations

import json
from collections import defaultdict

import numpy as np
from rasterio.crs import CRS
from rasterio.features import shapes
from rasterio.warp import transform_geom
from scipy import ndimage
from shapely.geometry import mapping, shape
from shapely.ops import unary_union

from .confidence import confidence_label

DISCLAIMER = ("Screening product generated by a student hackathon prototype from satellite radar data. "
              "Not an official flood map or emergency warning. Verify with official sources.")


def _round_coords(geom: dict, ndigits: int = 6) -> dict:
    def rnd(c):
        if isinstance(c, (list, tuple)) and c and isinstance(c[0], (int, float)):
            return [round(float(v), ndigits) for v in c]
        return [rnd(x) for x in c]
    return {"type": geom["type"], "coordinates": rnd(geom["coordinates"])}


def change_objects(mask: np.ndarray, transform, crs, pixel_area_m2: float,
                   layers: dict[str, np.ndarray], confidence: np.ndarray | None,
                   hazard: str, label: str) -> list[dict]:
    """Polygonise a boolean mask into GeoJSON features (EPSG:4326, lon/lat order).

    layers: named float arrays (e.g. delta_db, post_db) averaged per object.
    """
    if not mask.any():
        return []
    crs = CRS.from_user_input(crs)
    labels, n = ndimage.label(mask, structure=np.ones((3, 3), dtype=bool))
    idx = np.arange(1, n + 1)
    counts = ndimage.sum(mask, labels, idx)
    means = {name: ndimage.mean(np.nan_to_num(arr, nan=0.0), labels, idx) for name, arr in layers.items()}
    finite_counts = {name: ndimage.sum(np.isfinite(arr), labels, idx) for name, arr in layers.items()}
    if confidence is not None:
        conf_mean = ndimage.mean(np.nan_to_num(confidence, nan=0.0), labels, idx)

    pieces = defaultdict(list)
    for geom, value in shapes(labels.astype(np.int32), mask=mask, transform=transform, connectivity=8):
        pieces[int(value)].append(shape(geom))

    features = []
    for lab, geoms in pieces.items():
        i = lab - 1
        poly_native = unary_union(geoms)
        geom_ll = transform_geom(crs, "EPSG:4326", mapping(poly_native))
        centroid = shape(geom_ll).centroid
        props = {
            "hazard": hazard,
            "label": label,
            "area_km2": round(float(counts[i]) * pixel_area_m2 / 1e6, 4),
            "pixels": int(counts[i]),
            "centroid_lon": round(centroid.x, 5),
            "centroid_lat": round(centroid.y, 5),
        }
        for name in layers:
            # Mean over finite values only (NaNs were zero-filled above).
            fc = finite_counts[name][i]
            props[f"mean_{name}"] = (round(float(means[name][i] * counts[i] / fc), 2) if fc else None)
        if confidence is not None:
            score = round(float(conf_mean[i]), 3)
            props["confidence"] = score
            props["confidence_label"] = confidence_label(score)
        features.append({"type": "Feature", "geometry": _round_coords(geom_ll), "properties": props})

    features.sort(key=lambda f: (-(f["properties"].get("confidence") or 0), -f["properties"]["area_km2"]))
    for k, f in enumerate(features, start=1):
        f["properties"]["id"] = f"{hazard[:2].upper()}-{k:03d}"
    return features


def write_geojson(features: list[dict], path: str, extra: dict | None = None) -> None:
    fc = {"type": "FeatureCollection", "disclaimer": DISCLAIMER, **(extra or {}), "features": features}
    with open(path, "w") as f:
        json.dump(fc, f)
